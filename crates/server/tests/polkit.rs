use gilfoyle_core::Allowlist;
use gilfoyle_server::polkit::render_polkit_rule;

#[test]
fn renders_the_exact_rule_for_managed_units() {
    let allowlist = Allowlist::new(["nginx.service".to_string(), "sshd.socket".to_string()]);
    let expected = r#"// Generated by `gilfoyle systemd polkit-rule` from [systemd] manage_units.
// Install it with:
//   gilfoyle systemd polkit-rule | sudo tee /etc/polkit-1/rules.d/49-gilfoyle-units.rules > /dev/null
polkit.addRule(function(action, subject) {
    if (action.id != "org.freedesktop.systemd1.manage-units") return polkit.Result.NOT_HANDLED;
    if (subject.user != "gilfoyle") return polkit.Result.NOT_HANDLED;
    var verb = action.lookup("verb");
    if (verb != "start" && verb != "stop") return polkit.Result.NOT_HANDLED;
    var allowed = [
        "nginx.service",
        "sshd.socket"
    ];
    if (allowed.indexOf(action.lookup("unit")) === -1) return polkit.Result.NOT_HANDLED;
    return polkit.Result.YES;
});
"#;
    assert_eq!(render_polkit_rule(&allowlist), expected);
}

