//! Rendering of the polkit rule that authorises unit control.
//!
//! The configuration is the single source of truth: the rule is generated from
//! `[systemd] manage_units` and installed by the operator with `sudo`.

use gilfoyle_core::Allowlist;

/// Conventional install path for the generated rule.
pub const POLKIT_RULE_PATH: &str = "/etc/polkit-1/rules.d/49-gilfoyle-units.rules";

/// Render the polkit rule granting the `gilfoyle` user start/stop on managed units.
pub fn render_polkit_rule(allowlist: &Allowlist) -> String {
    let entries: Vec<String> = allowlist
        .names()
        .map(|name| format!("        \"{name}\""))
        .collect();
    let list = entries.join(",\n");
    format!(
        r#"// Generated by `gilfoyle systemd polkit-rule` from [systemd] manage_units.
// Install it with:
//   gilfoyle systemd polkit-rule | sudo tee {path} > /dev/null
polkit.addRule(function(action, subject) {{
    if (action.id != "org.freedesktop.systemd1.manage-units") return polkit.Result.NOT_HANDLED;
    if (subject.user != "gilfoyle") return polkit.Result.NOT_HANDLED;
    var verb = action.lookup("verb");
    if (verb != "start" && verb != "stop") return polkit.Result.NOT_HANDLED;
    var allowed = [
{list}
    ];
    if (allowed.indexOf(action.lookup("unit")) === -1) return polkit.Result.NOT_HANDLED;
    return polkit.Result.YES;
}});
"#,
        path = POLKIT_RULE_PATH,
        list = list,
    )
}
