//! Rendering of the polkit rule that authorises unit control.
//!
//! The configuration is the single source of truth: the rule is generated from
//! `[systemd] manage_units` and installed by the operator with `sudo`.

use gilfoyle_core::{Allowlist, PackageAllowlist, PackageOperation};

/// Conventional install path for the generated systemd rule.
pub const POLKIT_RULE_PATH: &str = "/etc/polkit-1/rules.d/49-gilfoyle-units.rules";

/// Conventional install path for the generated PackageKit rule.
pub const PACKAGEKIT_POLKIT_RULE_PATH: &str = "/etc/polkit-1/rules.d/49-gilfoyle-packagekit.rules";

/// Polkit actions gilfoyle must never hold, whatever `[packagekit] allow` says.
///
/// These cover installing, reinstalling, downgrading and removing packages,
/// trusting new signing keys and upgrading the whole distribution. The list is
/// fixed in code so that no configuration can widen it.
pub const DENIED_PACKAGEKIT_ACTIONS: [&str; 7] = [
    "org.freedesktop.packagekit.package-install",
    "org.freedesktop.packagekit.package-install-untrusted",
    "org.freedesktop.packagekit.package-reinstall",
    "org.freedesktop.packagekit.package-downgrade",
    "org.freedesktop.packagekit.package-remove",
    "org.freedesktop.packagekit.upgrade-system",
    "org.freedesktop.packagekit.system-trust-signing-key",
];

/// The polkit action backing a package operation.
pub fn package_operation_action(operation: PackageOperation) -> &'static str {
    match operation {
        PackageOperation::Refresh => "org.freedesktop.packagekit.system-sources-refresh",
        PackageOperation::Upgrade => "org.freedesktop.packagekit.system-update",
    }
}

/// Render the polkit rule authorising `gilfoyle` for the allowed package
/// operations, and refusing the dangerous ones outright.
pub fn render_packagekit_polkit_rule(allowlist: &PackageAllowlist) -> String {
    let allowed: Vec<String> = allowlist
        .operations()
        .map(|operation| format!("        \"{}\"", package_operation_action(operation)))
        .collect();
    let denied: Vec<String> = DENIED_PACKAGEKIT_ACTIONS
        .iter()
        .map(|action| format!("        \"{action}\""))
        .collect();
    format!(
        r#"// Generated by `gilfoyle packagekit polkit-rule` from [packagekit] allow.
// Install it with:
//   gilfoyle packagekit polkit-rule | sudo tee {path} > /dev/null
// It grants the `gilfoyle` user only the allowed package operations and
// explicitly refuses installing, reinstalling, downgrading or removing packages.
polkit.addRule(function(action, subject) {{
    if (subject.user != "gilfoyle") return polkit.Result.NOT_HANDLED;
    var denied = [
{denied}
    ];
    if (denied.indexOf(action.id) !== -1) return polkit.Result.NO;
    var allowed = [
{allowed}
    ];
    if (allowed.indexOf(action.id) !== -1) return polkit.Result.YES;
    return polkit.Result.NOT_HANDLED;
}});
"#,
        path = PACKAGEKIT_POLKIT_RULE_PATH,
        denied = denied.join(",\n"),
        allowed = allowed.join(",\n"),
    )
}

/// Render the polkit rule granting the `gilfoyle` user start/stop on managed units.
pub fn render_polkit_rule(allowlist: &Allowlist) -> String {
    let entries: Vec<String> = allowlist
        .names()
        .map(|name| format!("        \"{name}\""))
        .collect();
    let list = entries.join(",\n");
    format!(
        r#"// Generated by `gilfoyle systemd polkit-rule` from [systemd] manage_units.
// Install it with:
//   gilfoyle systemd polkit-rule | sudo tee {path} > /dev/null
polkit.addRule(function(action, subject) {{
    if (action.id != "org.freedesktop.systemd1.manage-units") return polkit.Result.NOT_HANDLED;
    if (subject.user != "gilfoyle") return polkit.Result.NOT_HANDLED;
    var verb = action.lookup("verb");
    if (verb != "start" && verb != "stop") return polkit.Result.NOT_HANDLED;
    var allowed = [
{list}
    ];
    if (allowed.indexOf(action.lookup("unit")) === -1) return polkit.Result.NOT_HANDLED;
    return polkit.Result.YES;
}});
"#,
        path = POLKIT_RULE_PATH,
        list = list,
    )
}
